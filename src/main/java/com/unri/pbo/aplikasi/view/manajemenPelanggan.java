private void loadPelangganFromDB() {
    daftarPelanggan.clear();
    String sql = "SELECT kode_pelanggan, nama, telepon, alamat FROM pelanggan ORDER BY kode_pelanggan ASC";
    try (Connection conn = Koneksi.getConnection();
         PreparedStatement ps = conn.prepareStatement(sql);
         ResultSet rs = ps.executeQuery()) {

        while (rs.next()) {
            String kode = rs.getString("kode_pelanggan");
            String nama = rs.getString("nama") != null ? rs.getString("nama") : "";
            String telp = rs.getString("telepon") != null ? rs.getString("telepon") : "";
            String alamat = rs.getString("alamat") != null ? rs.getString("alamat") : "";
            daftarPelanggan.add(new String[]{kode, nama, telp, alamat});
        }
    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this, "Gagal memuat pelanggan: " + ex.getMessage());
    }
}

private String generateIdPelangganFromDB() {
    String sql = "SELECT kode_pelanggan FROM pelanggan ORDER BY kode_pelanggan DESC LIMIT 1";
    try (Connection conn = Koneksi.getConnection();
         PreparedStatement ps = conn.prepareStatement(sql);
         ResultSet rs = ps.executeQuery()) {

        int next = 1;
        if (rs.next()) {
            String terakhir = rs.getString("kode_pelanggan");
            if (terakhir != null) {
                String angka = terakhir.replaceAll("[^0-9]", "");
                if (!angka.isEmpty()) {
                    next = Integer.parseInt(angka) + 1;
                }
            }
        }
        return String.format("PLG%03d", next);
    } catch (SQLException ex) {
        return "PLG001";
    }
}

private void muatTabel(List<String[]> data) {
    model.setRowCount(0);
    for (String[] row : data) {
        model.addRow(new Object[]{row[0], row[1], row[2], row[3]});
    }
}

private void resetForm() {
    txtId.setText(generateIdPelangganFromDB());
    txtNama.setText("");
    txtTelepon.setText("");
    txtAlamat.setText("");
    tblPelanggan.clearSelection();
}

private void isiFormDariTabel() {
    int r = tblPelanggan.getSelectedRow();
    if (r < 0) return;
    txtId.setText(model.getValueAt(r, 0).toString());
    txtNama.setText(model.getValueAt(r, 1).toString());
    txtTelepon.setText(model.getValueAt(r, 2).toString());
    txtAlamat.setText(model.getValueAt(r, 3).toString());
}

private boolean valid() {
    if (txtNama.getText().isBlank() || txtTelepon.getText().isBlank() || txtAlamat.getText().isBlank()) {
        JOptionPane.showMessageDialog(this, "Nama, telepon, dan alamat wajib diisi.");
        return false;
    }
    if (!txtTelepon.getText().trim().matches("\\d{8,15}")) {
        JOptionPane.showMessageDialog(this, "No. telepon harus angka 8-15 digit.");
        return false;
    }
    return true;
}

