    private void btnCariActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCariActionPerformed
    String keyword = txtCari.getText().trim().toLowerCase();
    if (keyword.isEmpty()) {
        muatTabel(daftarPelanggan);
        return;
    }

    List<String[]> hasil = new ArrayList<>();
    for (String[] row : daftarPelanggan) {
        if (row[0].toLowerCase().contains(keyword)
                || row[1].toLowerCase().contains(keyword)
                || row[2].toLowerCase().contains(keyword)
                || row[3].toLowerCase().contains(keyword)) {
            hasil.add(row);
        }
    }
    muatTabel(hasil);
    }//GEN-LAST:event_btnCariActionPerformed

